-- Comandô initial PostgreSQL schema.
-- Single consolidated migration: creates the complete current schema on an empty database.

BEGIN;

CREATE TYPE order_type AS ENUM ('COUNTER', 'TABLE');
CREATE TYPE order_status AS ENUM ('OPEN', 'AWAITING_PAYMENT', 'CLOSED', 'CANCELED');
CREATE TYPE payment_method AS ENUM ('CASH', 'DEBIT_CARD', 'CREDIT_CARD', 'PIX', 'OTHER');
CREATE TYPE order_adjustment_type AS ENUM ('DISCOUNT', 'SURCHARGE');
CREATE TYPE order_adjustment_mode AS ENUM ('PERCENT', 'FIXED');

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    deleted_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_unique UNIQUE (email)
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT roles_code_unique UNIQUE (code),
    CONSTRAINT roles_code_valid CHECK (code IN ('ADMIN', 'CASHIER', 'SERVER'))
);

INSERT INTO roles (code) VALUES
    ('ADMIN'),
    ('CASHIER'),
    ('SERVER');

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_roles_pk PRIMARY KEY (user_id, role_id),
    CONSTRAINT user_roles_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT user_roles_role_fk
        FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    description TEXT NULL,
    category VARCHAR(80) NOT NULL DEFAULT 'Uncategorized',
    price_cents BIGINT NOT NULL,
    image_url TEXT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT items_price_nonnegative CHECK (price_cents >= 0),
    CONSTRAINT items_category_not_blank CHECK (length(btrim(category)) > 0)
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_type order_type NOT NULL,
    status order_status NOT NULL,
    total_amount_cents BIGINT NOT NULL DEFAULT 0,
    table_code VARCHAR(64) NULL,
    label VARCHAR(160) NULL,
    opened_by_user_id BIGINT NOT NULL,
    closed_by_user_id BIGINT NULL,
    canceled_by_user_id BIGINT NULL,
    payment_requested_at TIMESTAMPTZ NULL,
    payment_requested_by_user_id BIGINT NULL,
    adjustment_type order_adjustment_type NULL,
    adjustment_mode order_adjustment_mode NULL,
    adjustment_value BIGINT NOT NULL DEFAULT 0,
    adjustment_cents BIGINT NOT NULL DEFAULT 0,
    apply_service_fee BOOLEAN NOT NULL DEFAULT FALSE,
    service_fee_basis_points INTEGER NOT NULL DEFAULT 0,
    service_fee_cents BIGINT NOT NULL DEFAULT 0,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    canceled_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT orders_total_nonnegative CHECK (total_amount_cents >= 0),
    CONSTRAINT orders_version_positive CHECK (version > 0),
    CONSTRAINT orders_table_code_by_type CHECK (
        (order_type = 'TABLE' AND table_code IS NOT NULL)
        OR (order_type = 'COUNTER' AND table_code IS NULL)
    ),
    CONSTRAINT orders_label_counter_only CHECK (
        label IS NULL OR order_type = 'COUNTER'
    ),
    CONSTRAINT orders_counter_must_be_closed CHECK (
        order_type <> 'COUNTER' OR status = 'CLOSED'
    ),
    CONSTRAINT orders_awaiting_payment_table_only CHECK (
        status <> 'AWAITING_PAYMENT' OR order_type = 'TABLE'
    ),
    CONSTRAINT orders_lifecycle_timestamps CHECK (
        (status = 'OPEN'
            AND payment_requested_at IS NULL AND closed_at IS NULL AND canceled_at IS NULL)
        OR (status = 'AWAITING_PAYMENT'
            AND payment_requested_at IS NOT NULL AND closed_at IS NULL AND canceled_at IS NULL)
        OR (status = 'CLOSED' AND closed_at IS NOT NULL AND canceled_at IS NULL)
        OR (status = 'CANCELED' AND canceled_at IS NOT NULL AND closed_at IS NULL)
    ),
    CONSTRAINT orders_closed_actor_required CHECK (
        status <> 'CLOSED' OR closed_by_user_id IS NOT NULL
    ),
    CONSTRAINT orders_canceled_actor_required CHECK (
        status <> 'CANCELED' OR canceled_by_user_id IS NOT NULL
    ),
    CONSTRAINT orders_payment_request_pair CHECK (
        (payment_requested_at IS NULL) = (payment_requested_by_user_id IS NULL)
    ),
    CONSTRAINT orders_adjustment_pair CHECK (
        (adjustment_type IS NULL) = (adjustment_mode IS NULL)
    ),
    CONSTRAINT orders_adjustment_none_is_zero CHECK (
        adjustment_type IS NOT NULL OR (adjustment_value = 0 AND adjustment_cents = 0)
    ),
    CONSTRAINT orders_adjustment_value_valid CHECK (
        adjustment_value >= 0
        AND (adjustment_mode IS DISTINCT FROM 'PERCENT' OR adjustment_value <= 10000)
    ),
    CONSTRAINT orders_adjustment_sign CHECK (
        adjustment_type IS NULL
        OR (adjustment_type = 'DISCOUNT' AND adjustment_cents <= 0)
        OR (adjustment_type = 'SURCHARGE' AND adjustment_cents >= 0)
    ),
    CONSTRAINT orders_service_fee_valid CHECK (
        service_fee_basis_points BETWEEN 0 AND 10000
        AND service_fee_cents >= 0
        AND (apply_service_fee OR (service_fee_basis_points = 0 AND service_fee_cents = 0))
    ),
    CONSTRAINT orders_opened_by_fk
        FOREIGN KEY (opened_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT orders_closed_by_fk
        FOREIGN KEY (closed_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT orders_canceled_by_fk
        FOREIGN KEY (canceled_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT orders_payment_requested_by_fk
        FOREIGN KEY (payment_requested_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE order_items (
    order_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    item_name_snapshot VARCHAR(160) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price_cents BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT order_items_pk PRIMARY KEY (order_id, item_id),
    CONSTRAINT order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT order_items_unit_price_nonnegative CHECK (unit_price_cents >= 0),
    CONSTRAINT order_items_order_fk
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT order_items_item_fk
        FOREIGN KEY (item_id) REFERENCES items (id) ON DELETE RESTRICT
);

CREATE TABLE order_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    method payment_method NOT NULL,
    amount_cents BIGINT NOT NULL,
    received_cents BIGINT NULL,
    change_cents BIGINT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT order_payments_amount_positive CHECK (amount_cents > 0),
    CONSTRAINT order_payments_cash_tender_pair CHECK (
        (received_cents IS NULL) = (change_cents IS NULL)
    ),
    CONSTRAINT order_payments_cash_tender_cash_only CHECK (
        received_cents IS NULL OR method = 'CASH'
    ),
    CONSTRAINT order_payments_cash_tender_valid CHECK (
        received_cents IS NULL
        OR (received_cents >= amount_cents AND change_cents = received_cents - amount_cents)
    ),
    CONSTRAINT order_payments_order_fk
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT
);

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT refresh_tokens_hash_unique UNIQUE (token_hash),
    CONSTRAINT refresh_tokens_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT refresh_tokens_expiry_valid CHECK (expires_at > created_at)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NULL,
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(80) NOT NULL,
    target_id VARCHAR(128) NULL,
    request_id VARCHAR(128) NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT audit_logs_actor_fk
        FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE settings (
    id SMALLINT PRIMARY KEY DEFAULT 1,
    service_fee_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    service_fee_basis_points INTEGER NOT NULL DEFAULT 1000,
    updated_by_user_id BIGINT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT settings_singleton CHECK (id = 1),
    CONSTRAINT settings_service_fee_valid CHECK (service_fee_basis_points BETWEEN 0 AND 10000),
    CONSTRAINT settings_updated_by_fk
        FOREIGN KEY (updated_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
);

INSERT INTO settings (id) VALUES (1);

-- Indexes backed by real queries. Partial and composite indexes stay aligned with the filters
-- and sort orders used by the repositories.
CREATE INDEX items_sellable_category_idx
    ON items (category, name)
    WHERE deleted_at IS NULL AND active;

CREATE INDEX orders_history_idx ON orders (created_at DESC, id DESC);
CREATE INDEX orders_status_created_idx ON orders (status, created_at DESC, id DESC);
CREATE INDEX orders_closed_at_idx ON orders (closed_at) WHERE status = 'CLOSED';
CREATE INDEX orders_canceled_at_idx ON orders (canceled_at) WHERE status = 'CANCELED';
CREATE UNIQUE INDEX orders_one_active_per_table_idx
    ON orders (table_code)
    WHERE order_type = 'TABLE' AND status IN ('OPEN', 'AWAITING_PAYMENT');

CREATE INDEX order_payments_order_id_idx ON order_payments (order_id);
CREATE INDEX refresh_tokens_user_active_idx
    ON refresh_tokens (user_id, expires_at)
    WHERE revoked_at IS NULL;
CREATE INDEX audit_logs_created_at_idx ON audit_logs (created_at DESC);

COMMIT;
