BEGIN;

CREATE TYPE order_type AS ENUM ('COUNTER', 'TABLE');
CREATE TYPE order_status AS ENUM ('OPEN', 'CLOSED', 'CANCELED');

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    deleted_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_unique UNIQUE (email)
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT roles_code_unique UNIQUE (code),
    CONSTRAINT roles_code_valid CHECK (code IN ('ADMIN', 'CASHIER', 'SERVER'))
);

INSERT INTO roles (code) VALUES
    ('ADMIN'),
    ('CASHIER'),
    ('SERVER');

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by_user_id BIGINT NULL,
    CONSTRAINT user_roles_pk PRIMARY KEY (user_id, role_id),
    CONSTRAINT user_roles_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT user_roles_role_fk
        FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT,
    CONSTRAINT user_roles_assigned_by_fk
        FOREIGN KEY (assigned_by_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX user_roles_role_id_idx ON user_roles (role_id);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    description TEXT NULL,
    price_cents BIGINT NOT NULL,
    image_url TEXT NULL,
    deleted_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT items_price_nonnegative CHECK (price_cents >= 0)
);

CREATE INDEX items_active_name_idx ON items (name) WHERE deleted_at IS NULL;

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_type order_type NOT NULL,
    status order_status NOT NULL,
    total_amount_cents BIGINT NOT NULL DEFAULT 0,
    table_code VARCHAR(64) NULL,
    opened_by_user_id BIGINT NOT NULL,
    closed_by_user_id BIGINT NULL,
    canceled_by_user_id BIGINT NULL,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    canceled_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT orders_total_nonnegative CHECK (total_amount_cents >= 0),
    CONSTRAINT orders_version_positive CHECK (version > 0),
    CONSTRAINT orders_table_code_by_type CHECK (
        (order_type = 'TABLE' AND table_code IS NOT NULL)
        OR (order_type = 'COUNTER' AND table_code IS NULL)
    ),
    CONSTRAINT orders_counter_must_be_closed CHECK (
        order_type <> 'COUNTER' OR status = 'CLOSED'
    ),
    CONSTRAINT orders_lifecycle_timestamps CHECK (
        (status = 'OPEN' AND closed_at IS NULL AND canceled_at IS NULL)
        OR (status = 'CLOSED' AND closed_at IS NOT NULL AND canceled_at IS NULL)
        OR (status = 'CANCELED' AND canceled_at IS NOT NULL AND closed_at IS NULL)
    ),
    CONSTRAINT orders_closed_actor_required CHECK (
        status <> 'CLOSED' OR closed_by_user_id IS NOT NULL
    ),
    CONSTRAINT orders_canceled_actor_required CHECK (
        status <> 'CANCELED' OR canceled_by_user_id IS NOT NULL
    ),
    CONSTRAINT orders_opened_by_fk
        FOREIGN KEY (opened_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT orders_closed_by_fk
        FOREIGN KEY (closed_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT orders_canceled_by_fk
        FOREIGN KEY (canceled_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX orders_history_idx ON orders (created_at DESC, id DESC);
CREATE INDEX orders_status_type_idx ON orders (status, order_type, opened_at DESC);
CREATE INDEX orders_table_open_idx ON orders (table_code) WHERE order_type = 'TABLE' AND status = 'OPEN';
CREATE UNIQUE INDEX orders_one_open_per_table_idx
    ON orders (table_code)
    WHERE order_type = 'TABLE' AND status = 'OPEN';

CREATE TABLE order_items (
    order_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    item_name_snapshot VARCHAR(160) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price_cents BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT order_items_pk PRIMARY KEY (order_id, item_id),
    CONSTRAINT order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT order_items_unit_price_nonnegative CHECK (unit_price_cents >= 0),
    CONSTRAINT order_items_order_fk
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT order_items_item_fk
        FOREIGN KEY (item_id) REFERENCES items (id) ON DELETE RESTRICT
);

CREATE INDEX order_items_item_id_idx ON order_items (item_id);

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT refresh_tokens_hash_unique UNIQUE (token_hash),
    CONSTRAINT refresh_tokens_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT refresh_tokens_expiry_valid CHECK (expires_at > created_at)
);

CREATE INDEX refresh_tokens_user_active_idx
    ON refresh_tokens (user_id, expires_at)
    WHERE revoked_at IS NULL;

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NULL,
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(80) NOT NULL,
    target_id VARCHAR(128) NULL,
    request_id VARCHAR(128) NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT audit_logs_actor_fk
        FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX audit_logs_created_at_idx ON audit_logs (created_at DESC);
CREATE INDEX audit_logs_actor_created_at_idx ON audit_logs (actor_user_id, created_at DESC);
CREATE INDEX audit_logs_target_idx ON audit_logs (target_type, target_id);

COMMIT;
