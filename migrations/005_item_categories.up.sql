-- Categories are shared labels. Items keep `category` as their primary label for the
-- existing catalog grouping and search, while this relation holds the complete set.
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    normalized_name VARCHAR(80) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT categories_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE TABLE item_categories (
    item_id BIGINT NOT NULL REFERENCES items (id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (item_id, category_id)
);

CREATE INDEX item_categories_category_idx ON item_categories (category_id, item_id);

-- Keep the existing single-category catalog usable after the migration.
INSERT INTO categories (name, normalized_name)
SELECT DISTINCT i.category, lower(btrim(i.category))
FROM items i
WHERE i.category <> 'Uncategorized'
ON CONFLICT (normalized_name) DO NOTHING;

INSERT INTO item_categories (item_id, category_id)
SELECT i.id, c.id
FROM items i
JOIN categories c ON c.normalized_name = lower(btrim(i.category))
WHERE i.category <> 'Uncategorized'
ON CONFLICT (item_id, category_id) DO NOTHING;
