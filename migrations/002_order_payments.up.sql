-- Record the payment methods and amounts applied to closed orders.

BEGIN;

CREATE TYPE payment_method AS ENUM (
    'CASH',
    'DEBIT_CARD',
    'CREDIT_CARD',
    'PIX',
    'OTHER'
);

CREATE TABLE order_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    method payment_method NOT NULL,
    amount_cents BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT order_payments_amount_positive CHECK (amount_cents > 0),
    CONSTRAINT order_payments_order_fk
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT
);

CREATE INDEX order_payments_order_id_idx ON order_payments (order_id);

COMMIT;
