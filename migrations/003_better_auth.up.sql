-- Replace the custom credential/role tables with the schema used by Better Auth.
-- `users` is kept as the Better Auth user table so existing foreign keys stay valid.

BEGIN;

DROP TABLE refresh_tokens;
DROP TABLE user_roles;
DROP TABLE roles;

ALTER TABLE users
    DROP COLUMN password_hash,
    DROP COLUMN deleted_at,
    ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN image TEXT NULL,
    ADD COLUMN role TEXT NOT NULL DEFAULT 'SERVER',
    ADD COLUMN banned BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN ban_reason TEXT NULL,
    ADD COLUMN ban_expires TIMESTAMPTZ NULL,
    ADD CONSTRAINT users_role_valid CHECK (
        role ~ '^(ADMIN|CASHIER|SERVER)(,(ADMIN|CASHIER|SERVER))*$'
    );

CREATE TABLE sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    ip_address TEXT NULL,
    user_agent TEXT NULL,
    impersonated_by BIGINT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT sessions_token_unique UNIQUE (token),
    CONSTRAINT sessions_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX sessions_user_id_idx ON sessions (user_id);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_id TEXT NOT NULL,
    provider_id TEXT NOT NULL,
    password TEXT NULL,
    access_token TEXT NULL,
    refresh_token TEXT NULL,
    id_token TEXT NULL,
    access_token_expires_at TIMESTAMPTZ NULL,
    refresh_token_expires_at TIMESTAMPTZ NULL,
    scope TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT accounts_provider_unique UNIQUE (provider_id, account_id),
    CONSTRAINT accounts_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX accounts_user_id_idx ON accounts (user_id);

CREATE TABLE verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier TEXT NOT NULL,
    value TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX verifications_identifier_idx ON verifications (identifier);

COMMIT;
